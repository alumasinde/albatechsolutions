<?php
declare(strict_types=1);

$root = dirname(__DIR__);
$sourceDir = $root . '/public_html/assets/css/v5';
$output = $sourceDir . '/production.css';

$sources = [
    $root . '/public_html/assets/css/v4/production.css',
    $sourceDir . '/tokens.css',
    $sourceDir . '/shared.css',
    $sourceDir . '/public.css',
    $sourceDir . '/admin.css',
    $sourceDir . '/compatibility.css',
];

$css = "/* AlbaTech Solutions — production.css (v5)\n"
    . " * Generated by: php bin/build-css.php\n"
    . " * Do not edit this file directly.\n"
    . " */\n\n";

foreach ($sources as $source) {
    if (!is_file($source)) {
        fwrite(STDERR, "Missing CSS source: {$source}\n");
        exit(1);
    }

    $content = file_get_contents($source);
    if ($content === false) {
        fwrite(STDERR, "Unable to read CSS source: {$source}\n");
        exit(1);
    }

    $css .= "\n/* ===== " . basename($source) . " ===== */\n" . trim($content) . "\n";
}

if (file_put_contents($output, $css) === false) {
    fwrite(STDERR, "Unable to write {$output}\n");
    exit(1);
}

echo "Built " . str_replace($root . DIRECTORY_SEPARATOR, '', $output) . " from " . count($sources) . " sources.\n";
